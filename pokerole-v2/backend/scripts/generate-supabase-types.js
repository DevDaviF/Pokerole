const { execFileSync } = require('node:child_process');
const { writeFileSync } = require('node:fs');
const path = require('node:path');
const { config } = require('dotenv');

config({ path: path.join(__dirname, '..', '.env') });

const supabaseUrl = process.env.SUPABASE_URL;
if (!supabaseUrl) {
  throw new Error('SUPABASE_URL is required in .env');
}

const projectIdMatch = /^https:\/\/([a-z0-9-]+)\.supabase\.co\/?$/i.exec(
  supabaseUrl,
);
if (!projectIdMatch) {
  throw new Error(
    `SUPABASE_URL must match "https://{db-id}.supabase.co" (got: ${supabaseUrl})`,
  );
}

const projectId = projectIdMatch[1];

const supabaseCli = path.join(
  path.dirname(require.resolve('supabase/package.json')),
  'dist',
  'supabase.js',
);

const output = execFileSync(
  process.execPath,
  [
    supabaseCli,
    'gen',
    'types',
    'typescript',
    '--project-id',
    projectId,
    '--schema',
    'public',
  ],
  {
    encoding: 'utf8',
    env: process.env,
  },
);

const content = `/**\n * This file is auto-generated by the supabase:types script.\n * Do not edit this file manually.\n */\n\n/* eslint-disable */\n\n${output}`;

writeFileSync('src/database/database.types.ts', content, 'utf8');
